using System;
using System.Collections.Generic;
using System.Linq;
using System.Text;
using System.Threading;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using Microsoft.CodeAnalysis.Text;

namespace SP.Engine.SourceGenerator
{
    [Generator(LanguageNames.CSharp)]
    public sealed class ProtocolHandlerGenerator : IIncrementalGenerator
    {
        public void Initialize(IncrementalGeneratorInitializationContext context)
        {
            var provider = context.SyntaxProvider
                .ForAttributeWithMetadataName(
                    KnownSymbols.ProtocolHandlerAttribute,
                    predicate: static (node, _) => node is ClassDeclarationSyntax,
                    transform: static (ctx, ct) => TransformHandlerClass(ctx, ct))
                .Where(static m => m != null);

            var collected = provider.Collect();
            context.RegisterSourceOutput(collected, static (spc, models) =>
            {
                if (models.IsDefaultOrEmpty) return;

                var seenKeys = new HashSet<string>();
                var uniqueModels = new List<ProtocolHandlerModel>(models.Length);

                foreach (var model in models)
                {
                    if (model == null) continue;

                    var key = $"{model.ContextFullTypeName}:{model.Id}";
                    if (!seenKeys.Add(key))
                    {
                        spc.ReportDiagnostic(Diagnostic.Create(
                            Diagnostics.DuplicateProtocolHandlerId,
                            Location.None,
                            model.Id,
                            model.ContextFullTypeName,
                            model.HandlerFullTypeName));
                        continue;
                    }

                    uniqueModels.Add(model);
                }

                if (uniqueModels.Count == 0) return;

                var source = BuildProtocolHandlerRegistrySource(uniqueModels);
                spc.AddSource("ProtocolHandlerRegistry.g.cs", SourceText.From(source, Encoding.UTF8));
            });
        }

        private static ProtocolHandlerModel? TransformHandlerClass(GeneratorAttributeSyntaxContext ctx, CancellationToken ct)
        {
            if (ctx.TargetSymbol is not INamedTypeSymbol symbol || symbol.IsAbstract || symbol.IsGenericType)
                return null;

            var attr = ctx.Attributes.FirstOrDefault();
            if (attr == null || attr.ConstructorArguments.Length == 0 || attr.ConstructorArguments[0].Value == null)
                return null;

            var id = Convert.ToUInt16(attr.ConstructorArguments[0].Value);

            ITypeSymbol? contextType = null;
            var baseType = symbol.BaseType;
            while (baseType != null && baseType.SpecialType != SpecialType.System_Object)
            {
                ct.ThrowIfCancellationRequested();
                if (baseType is { IsGenericType: true, Name: KnownSymbols.ProtocolHandlerBase } &&
                    baseType.ContainingNamespace?.ToDisplayString() == KnownSymbols.ProtocolHandlerBaseNamespace &&
                    baseType.TypeArguments.Length >= 1)
                {
                    contextType = baseType.TypeArguments[0];
                    break;
                }
                baseType = baseType.BaseType;
            }

            if (contextType == null)
                return null;

            var handlerFullTypeName = symbol.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
            var contextFullTypeName = contextType.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
            var assemblyName = IdentifierHelper.Sanitize(symbol.ContainingAssembly?.Name ?? "Assembly");

            return new ProtocolHandlerModel(assemblyName, id, handlerFullTypeName, contextFullTypeName);
        }

        private static string BuildProtocolHandlerRegistrySource(List<ProtocolHandlerModel> models)
        {
            var className = $"ProtocolHandlerRegistry_{models[0].AssemblyName}";
            
            var sb = new StringBuilder();
            sb.AppendLine("// <auto-generated/>");
            sb.AppendLine($"[assembly: {KnownSymbols.GlobalProtocolHandlerRegistryAttr}(typeof(global::{KnownSymbols.GlobalNamespace}.{className}))]");
            sb.AppendLine();
            sb.AppendLine($"namespace {KnownSymbols.GlobalNamespace}");
            sb.AppendLine("{");
            sb.AppendLine($"     internal sealed class {className} : {KnownSymbols.GlobalIProtocolHandlerRegistry}");
            sb.AppendLine("     {");
            sb.AppendLine("         public void Register(");
            sb.AppendLine($"             global::System.Collections.Generic.IDictionary<ushort, {KnownSymbols.GlobalIProtocolHandler}> handlers,");
            sb.AppendLine("             global::System.Func<global::System.Type, bool> contextFilter)");
            sb.AppendLine("         {");

            foreach (var group in models.GroupBy(m => m.ContextFullTypeName))
            {
                sb.AppendLine($"             if (contextFilter == null || contextFilter(typeof({group.Key})))");
                sb.AppendLine("             {");

                foreach (var item in group)
                {
                    sb.AppendLine($"                    handlers[{item.Id}] = new {item.HandlerFullTypeName}();");
                }

                sb.AppendLine("             }");
            }

            sb.AppendLine("         }");
            sb.AppendLine("    }");
            sb.AppendLine("}");
            
            return sb.ToString();
        }
    }
}
