using System;
using System.Collections.Generic;
using System.IO;
using System.Linq;
using System.Text;
using SP.Resource.Table;

namespace SP.Resource.CodeGen;

public static class ReferenceCodeGenerator
{
    public const string DefaultNamespace = "SP.Resource.Generated";

    public static void Generate(
        IReadOnlyList<RefTableSchema> schemas,
        string outputDir,
        string @namespace = DefaultNamespace)
    {
        Directory.CreateDirectory(outputDir);

        foreach (var schema in schemas)
        {
            var className = GetClassName(schema);
            var filePath = Path.Combine(outputDir, $"{className}.cs");

            var code = GenerateCSharpCode(schema, @namespace);
            File.WriteAllText(filePath, code, Encoding.UTF8);
        }
    }

    public static string GenerateCSharpCode(
        RefTableSchema schema,
        string @namespace = DefaultNamespace)
    {
        var keyColumn = schema.Columns.FirstOrDefault(c => c.IsKey)
            ?? throw new InvalidOperationException($"Table '{schema.Name}' must have at least one key.");

        var className = GetClassName(schema);
        var keyTypeName = GetCSharpType(keyColumn.Type);
        var keyPropName = ToIdentifier(keyColumn.Name);
        var dicName = GetDictionaryName(schema);
        var buildMethodName = GetBuildMethodName(schema);

        var sb = new StringBuilder();
        sb.AppendLine("// <auto-generated/>");
        sb.AppendLine("#nullable enable");
        sb.AppendLine();
        sb.AppendLine("using System;");
        sb.AppendLine("using System.Collections.Generic;");
        sb.AppendLine("using SP.Resource.Table;");
        sb.AppendLine();
        sb.AppendLine($"namespace {@namespace}");
        sb.AppendLine("{");

        AppendRefClass(sb, schema, className);
        sb.AppendLine();
        AppendManagerPartial(sb, schema, className, keyTypeName, keyPropName, dicName, buildMethodName);

        sb.AppendLine("}");

        return sb.ToString();
    }

    private static void AppendRefClass(
        StringBuilder sb,
        RefTableSchema schema,
        string className)
    {
        sb.AppendLine($"    public sealed class {className}");
        sb.AppendLine("    {");

        foreach (var column in schema.Columns)
        {
            var typeName = GetCSharpType(column.Type);
            var propName = ToIdentifier(column.Name);
            var defaultVal = typeName == "string" ? " = string.Empty;" : "";
            sb.AppendLine($"        public {typeName} {propName} {{ get; private set; }}{defaultVal}");
        }

        sb.AppendLine();

        var createArgs = string.Join(", ", schema.Columns.Select(c => $"int idx{ToIdentifier(c.Name)}"));
        sb.AppendLine($"        public static {className} Create(RefRow row, {createArgs})");
        sb.AppendLine("        {");
        sb.AppendLine($"            return new {className}");
        sb.AppendLine("            {");

        for (var i = 0; i < schema.Columns.Count; i++)
        {
            var column = schema.Columns[i];
            var propName = ToIdentifier(column.Name);
            var methodName = GetRowMethodName(column.Type);
            var suffix = i == schema.Columns.Count - 1 ? "" : ",";
            sb.AppendLine($"                {propName} = row.{methodName}(idx{propName}){suffix}");
        }

        sb.AppendLine("            };");
        sb.AppendLine("        }");
        sb.AppendLine("    }");
    }

    private static void AppendManagerPartial(
        StringBuilder sb,
        RefTableSchema schema,
        string className,
        string keyTypeName,
        string keyPropName,
        string dicName,
        string buildMethodName)
    {
        sb.AppendLine("    public sealed partial class ReferenceTableManager");
        sb.AppendLine("    {");
        sb.AppendLine($"        public Dictionary<{keyTypeName}, {className}> {dicName} {{ get; private set; }} = new();");
        sb.AppendLine();
        sb.AppendLine($"        private void {buildMethodName}()");
        sb.AppendLine("        {");
        sb.AppendLine($"            const string tableName = \"{schema.Name}\";");
        sb.AppendLine("            if (!TryGet(tableName, out var schema, out var table))");
        sb.AppendLine("            {");
        sb.AppendLine("                return;");
        sb.AppendLine("            }");
        sb.AppendLine();

        foreach (var column in schema.Columns)
        {
            var propName = ToIdentifier(column.Name);
            sb.AppendLine($"            var idx{propName} = schema.GetColumnIndex(\"{column.Name}\");");
        }

        sb.AppendLine();
        sb.AppendLine($"            var dict = new Dictionary<{keyTypeName}, {className}>(table.Rows.Count);");
        sb.AppendLine("            foreach (var row in table.Rows)");
        sb.AppendLine("            {");

        var createCallArgs = string.Join(", ", schema.Columns.Select(c => $"idx{ToIdentifier(c.Name)}"));
        sb.AppendLine($"                var obj = {className}.Create(row, {createCallArgs});");
        sb.AppendLine($"                dict[obj.{keyPropName}] = obj;");
        sb.AppendLine("            }");
        sb.AppendLine();
        sb.AppendLine($"            {dicName} = dict;");
        sb.AppendLine("        }");
        sb.AppendLine();
        sb.AppendLine($"        public {className}? Get{className}({keyTypeName} id)");
        sb.AppendLine("        {");
        sb.AppendLine($"            return {dicName}.TryGetValue(id, out var v) ? v : null;");
        sb.AppendLine("        }");
        sb.AppendLine("    }");
    }

    private static string GetClassName(RefTableSchema schema)
        => "Ref" + ToPascal(schema.Name);

    private static string GetDictionaryName(RefTableSchema schema)
    {
        var n = ToPascal(schema.Name);
        return n.EndsWith("s") ? n : n + "s";
    }

    private static string GetBuildMethodName(RefTableSchema schema)
        => "Build" + GetClassName(schema);

    private static string GetCSharpType(ColumnType type)
    {
        return type switch
        {
            ColumnType.String => "string",
            ColumnType.Byte => "byte",
            ColumnType.Int32 => "int",
            ColumnType.Int64 => "long",
            ColumnType.Float => "float",
            ColumnType.Double => "double",
            ColumnType.Boolean => "bool",
            ColumnType.DateTime => "DateTime",
            _ => "object"
        };
    }

    private static string GetRowMethodName(ColumnType type)
    {
        return type switch
        {
            ColumnType.String => "GetString",
            ColumnType.Byte => "GetByte",
            ColumnType.Int32 => "GetInt32",
            ColumnType.Int64 => "GetInt64",
            ColumnType.Float => "GetSingle",
            ColumnType.Double => "GetDouble",
            ColumnType.Boolean => "GetBoolean",
            ColumnType.DateTime => "GetDateTime",
            _ => "GetString"
        };
    }

    private static string ToPascal(string name)
    {
        var parts = name
            .Split(new[] { '_', ' ', '-' }, StringSplitOptions.RemoveEmptyEntries);

        return string.Concat(
            parts.Select(p => char.ToUpperInvariant(p[0]) + p[1..]));
    }

    private static string ToIdentifier(string name)
    {
        var pascal = ToPascal(name);
        if (!string.IsNullOrEmpty(pascal) && char.IsDigit(pascal[0]))
            pascal = "_" + pascal;
        return pascal;
    }
}
